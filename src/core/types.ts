// ─── Intake ──────────────────────────────────────────────────────────────────

export type IntakeChannel = "WHATSAPP" | "EMAIL" | "VOICE_NOTE" | "PDF" | "IMAGE";

export interface ExtractedField<T> {
  value: T | null;
  confidence: number; // [0,1]
  source: string; // which fragment of the raw message it came from
}

export interface IntakeExtraction {
  origin: ExtractedField<string>;
  destination: ExtractedField<string>;
  commodity: ExtractedField<string>;
  weightKg: ExtractedField<number>;
  volumeCbm: ExtractedField<number>;
  pieces: ExtractedField<number>;
  incoterm: ExtractedField<Incoterm>;
  mode: ExtractedField<TransportMode>;
  neededBy: ExtractedField<string>;
  customerName: ExtractedField<string>;
  /** Mean confidence across populated fields. */
  overallConfidence: number;
}

export interface IntakeMessage {
  id: string;
  channel: IntakeChannel;
  from: string;
  receivedAt: string;
  raw: string;
  extraction?: IntakeExtraction;
  status: "NEW" | "PARSED" | "CONVERTED" | "REJECTED";
  shipmentId?: string;
  /** Which engine produced the extraction: the live LLM or the local parser. */
  parsedBy?: string;
}

// ─── The Agent ───────────────────────────────────────────────────────────────

/**
 * Autonomy is earned in four notches, per task type:
 *  1 SUGGEST — propose, human does it.
 *  2 DRAFT   — prepare the action, human sends it.
 *  3 APPROVE — execute after one-tap human approval.
 *  4 AUTO    — execute automatically, report after.
 */
export type AutonomyLevel = 1 | 2 | 3 | 4;

export type AgentTaskType =
  | "QUOTE"
  | "BOOKING"
  | "DOCUMENTS"
  | "CUSTOMER_UPDATE"
  | "EXCEPTION_HANDLING"
  | "COLLECTIONS";

export interface AutonomyGrant {
  taskType: AgentTaskType;
  level: AutonomyLevel;
  /** Successful actions completed at or above current level. */
  earnedOver: number;
  /** USD value above which the agent always escalates regardless of level. */
  valueCeiling: number;
}

export type AgentActionStatus =
  | "SUGGESTED"
  | "DRAFTED"
  | "AWAITING_APPROVAL"
  | "EXECUTED"
  | "ESCALATED"
  | "REJECTED";

export interface AgentAction {
  id: string;
  shipmentId: string;
  taskType: AgentTaskType;
  levelUsed: AutonomyLevel;
  summary: string;
  detail: string;
  confidence: number; // [0,1]
  valueAtStake: number; // USD
  status: AgentActionStatus;
  at: string;
  escalationReason?: string;
}

