// ─── THE SHIPMENT ────────────────────────────────────────────────────────────

export interface Shipment {
  id: string; // ENG-2026-XXXX
  ref: string; // human-friendly
  state: ShipmentState;
  customerId: string;
  origin: string; // UN/LOCODE + city
  destination: string;
  mode: TransportMode;
  incoterm: Incoterm;
  cargo: Cargo;
  carrier?: string;
  vesselOrFlight?: string;
  neededBy?: string;
  createdAt: string;
  stateEnteredAt: string;
  /** Money view */
  revenue: number;
  cost: number;
  /** Live operational view */
  eta?: EtaPrediction;
  hasOpenException: boolean;
  /** Provenance */
  sourceIntakeId?: string;
}
